export interface LawContext {
  taxRates: string;
  accountingStandards: string;
  civilCommercialLaw: string;
}

/**
 * 과목에 맞는 법령 컨텍스트 반환
 */
export function getLawContext(subject: string, topic: string): string {
  const parts: string[] = [];

  // 세법 과목
  if (subject.includes("세법") || subject.includes("재정학")) {
    parts.push(TAX_RATES_2025);
  }

  // 회계 과목
  if (subject.includes("회계")) {
    parts.push(ACCOUNTING_STANDARDS_2025);
    // 세법회계(법인세회계)면 세율도 포함
    if (topic.includes("법인세") || topic.includes("세")) {
      parts.push(TAX_RATES_2025);
    }
  }

  // 상법·민법
  if (subject.includes("상법") || subject.includes("민법") || subject.includes("행정")) {
    parts.push(CIVIL_COMMERCIAL_LAW);
  }

  if (parts.length === 0) {
    parts.push(TAX_RATES_2025); // fallback
  }

  return parts.join("\n\n");
}
